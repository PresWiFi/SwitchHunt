<#
    Test-InSandbox.ps1 - try this Intune bundle in Windows Sandbox before any real device sees it.
    Generated by SwitchHunt. Start it with Test-InSandbox.cmd (double-click).

    On this PC it opens a fresh Windows Sandbox with this folder mapped into it, then waits.
    Inside the Sandbox it does what Intune does, in the same order, as SYSTEM:

      1. Unpacks the .intunewin with the keys in its Detection.xml (HMAC checked, AES decrypted).
      2. Runs Detect.ps1          - expected: NOT installed (the Sandbox is a clean Windows).
      3. Runs Install.ps1         - as SYSTEM, from 32-bit PowerShell, like the Intune agent.
      4. Runs Detect.ps1          - expected: installed.
      5. Records what the install added to Programs and Features: the exact display name,
         version, product code, uninstall command and main program file. Load report.json into
         the SwitchHunt page ("Load sandbox results") to use them for detection and uninstall.
      6. Runs Uninstall.ps1, then Detect.ps1 again - expected: NOT installed.

    Results land next to this script in SandboxResults\<date-time>\ (report.txt, report.json and
    every log). Needs Windows 10/11 Pro or Enterprise with the Windows Sandbox feature turned on.
    Limits: no reboots (a 3010/1641 result is reported, not acted on), and apps that need
    virtualization themselves (Docker Desktop, WSL, Hyper-V tools) cannot run inside the Sandbox.
#>
param(
    [switch]$InSandbox,
    [string]$RunId
)

$ErrorActionPreference = 'Stop'
$InstallTimeoutMinutes = 60     # Intune's default for a Win32 app
$DetectTimeoutMinutes  = 5
$Here = $PSScriptRoot

# ─────────────────────────────── on this PC ───────────────────────────────
if (-not $InSandbox) {
    $sandboxExe = Join-Path $env:WINDIR 'System32\WindowsSandbox.exe'
    if (-not (Test-Path $sandboxExe)) {
        Write-Host 'Windows Sandbox is not turned on for this PC.' -ForegroundColor Yellow
        Write-Host 'Turn it on (needs Windows Pro or Enterprise, admin rights and a reboot) with:'
        Write-Host '    Enable-WindowsOptionalFeature -Online -FeatureName Containers-DisposableClientVM -All'
        Write-Host 'or: Settings > System > Optional features > More Windows features > Windows Sandbox.'
        Read-Host 'Press Enter to close'
        exit 1
    }
    if (Get-Process -Name 'WindowsSandboxClient', 'WindowsSandboxRemoteSession' -ErrorAction SilentlyContinue) {
        Write-Host 'A Windows Sandbox is already open - only one can run at a time. Close it and try again.' -ForegroundColor Yellow
        Read-Host 'Press Enter to close'
        exit 1
    }
    if (-not (Get-ChildItem -LiteralPath $Here -Filter '*.intunewin' -File)) {
        Write-Host "No .intunewin next to this script ($Here). Unzip the whole bundle and run it from there." -ForegroundColor Yellow
        Read-Host 'Press Enter to close'
        exit 1
    }

    $runId   = Get-Date -Format 'yyyyMMdd-HHmmss'
    $results = Join-Path $Here "SandboxResults\$runId"
    New-Item -ItemType Directory -Path $results -Force | Out-Null
    $esc = [Security.SecurityElement]::Escape($Here)
    $wsb = Join-Path $env:TEMP "SwitchHunt-$runId.wsb"
    @"
<Configuration>
  <MappedFolders>
    <MappedFolder>
      <HostFolder>$esc</HostFolder>
      <SandboxFolder>C:\Bundle</SandboxFolder>
      <ReadOnly>false</ReadOnly>
    </MappedFolder>
  </MappedFolders>
  <MemoryInMB>4096</MemoryInMB>
  <LogonCommand>
    <Command>powershell.exe -ExecutionPolicy Bypass -NoProfile -File C:\Bundle\Test-InSandbox.ps1 -InSandbox -RunId $runId</Command>
  </LogonCommand>
</Configuration>
"@ | Set-Content -LiteralPath $wsb -Encoding UTF8

    Write-Host "Starting Windows Sandbox. Results: $results"
    Write-Host 'The test runs by itself inside the Sandbox window - leave it open until this window says it is done.'
    Start-Process -FilePath $wsb
    $progress = Join-Path $results 'progress.log'
    $report   = Join-Path $results 'report.txt'
    $shown = 0
    $deadline = (Get-Date).AddMinutes(2 * $InstallTimeoutMinutes + 4 * $DetectTimeoutMinutes + 15)
    while (-not (Test-Path $report) -and (Get-Date) -lt $deadline) {
        Start-Sleep -Seconds 3
        if (Test-Path $progress) {
            $lines = @(Get-Content -LiteralPath $progress -ErrorAction SilentlyContinue)
            $lines | Select-Object -Skip $shown | ForEach-Object { Write-Host "  $_" }
            $shown = $lines.Count
        }
    }
    Remove-Item -LiteralPath $wsb -ErrorAction SilentlyContinue
    if (Test-Path $report) {
        Write-Host ''
        Get-Content -LiteralPath $report | Write-Host
        Start-Process notepad.exe -ArgumentList "`"$report`""
        Write-Host ''
        Write-Host 'You can close the Sandbox now (everything in it is thrown away).'
    } else {
        Write-Host 'No report arrived. Check the Sandbox window, and progress.log in the results folder.' -ForegroundColor Yellow
    }
    Read-Host 'Press Enter to close'
    exit 0
}

# ─────────────────────────────── in the Sandbox ───────────────────────────────
# Registering a task that runs as SYSTEM needs an elevated shell.
$principal = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    Start-Process powershell.exe -Verb RunAs -ArgumentList "-ExecutionPolicy Bypass -NoProfile -File `"$PSCommandPath`" -InSandbox -RunId $RunId"
    exit 0
}
$results = Join-Path $Here "SandboxResults\$RunId"
New-Item -ItemType Directory -Path $results -Force | Out-Null
$work = 'C:\SwitchHuntTest'
New-Item -ItemType Directory -Path $work -Force | Out-Null
$steps = New-Object System.Collections.ArrayList

function Write-Progress2([string]$Text) {
    $line = "$(Get-Date -Format 'HH:mm:ss')  $Text"
    Write-Host $line
    Add-Content -LiteralPath (Join-Path $results 'progress.log') -Value $line
}
function Add-Step([string]$Name, [bool]$Ok, [string]$Detail) {
    [void]$steps.Add([ordered]@{ step = $Name; ok = $Ok; detail = $Detail })
    Write-Progress2 ("{0}  {1} - {2}" -f $(if ($Ok) { 'PASS' } else { 'FAIL' }), $Name, $Detail)
}

# Run a command as SYSTEM through a scheduled task - the same account Intune installs with.
# Returns @{ ExitCode; Output; TimedOut }.
function Invoke-AsSystem([string]$Exe, [string]$Arguments, [string]$WorkDir, [int]$TimeoutMinutes) {
    $name = 'SwitchHuntTest-' + [guid]::NewGuid().ToString('N')
    $out  = Join-Path $work "$name.out"
    $cmdLine = "/c `"`"$Exe`" $Arguments > `"$out`" 2>&1`""
    $action    = New-ScheduledTaskAction -Execute 'cmd.exe' -Argument $cmdLine -WorkingDirectory $WorkDir
    $principal = New-ScheduledTaskPrincipal -UserId 'S-1-5-18' -LogonType ServiceAccount -RunLevel Highest
    $settings  = New-ScheduledTaskSettingsSet -ExecutionTimeLimit (New-TimeSpan -Minutes ($TimeoutMinutes + 5)) -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries
    Register-ScheduledTask -TaskName $name -Action $action -Principal $principal -Settings $settings | Out-Null
    Start-ScheduledTask -TaskName $name
    $deadline = (Get-Date).AddMinutes($TimeoutMinutes)
    $timedOut = $false
    # 0x41301 = running, 0x41303 = has not run yet, 0x41325 = queued: anything else is the exit code.
    do {
        Start-Sleep -Seconds 2
        $code = (Get-ScheduledTaskInfo -TaskName $name).LastTaskResult
        $busy = (Get-ScheduledTask -TaskName $name).State -eq 'Running' -or $code -in 0x41301, 0x41303, 0x41325
        if ($busy -and (Get-Date) -gt $deadline) { Stop-ScheduledTask -TaskName $name; $timedOut = $true; break }
    } while ($busy)
    Unregister-ScheduledTask -TaskName $name -Confirm:$false
    $text = if (Test-Path $out) { (Get-Content -LiteralPath $out -Raw -ErrorAction SilentlyContinue) } else { '' }
    return @{ ExitCode = [int]$code; Output = "$text".Trim(); TimedOut = $timedOut }
}

# Everything listed under Programs and Features: machine-wide (64- and 32-bit) and SYSTEM's own.
function Get-UninstallEntries {
    $list = @{}
    $roots = @(
        @{ Hive = 'LocalMachine'; View = 'Registry64'; Path = 'SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall'; Label = 'HKLM' },
        @{ Hive = 'LocalMachine'; View = 'Registry32'; Path = 'SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall'; Label = 'HKLM (32-bit)' },
        @{ Hive = 'Users'; View = 'Registry64'; Path = 'S-1-5-18\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall'; Label = 'SYSTEM user' }
    )
    foreach ($r in $roots) {
        try { $base = [Microsoft.Win32.RegistryKey]::OpenBaseKey($r.Hive, $r.View).OpenSubKey($r.Path) } catch { continue }
        if (-not $base) { continue }
        foreach ($k in $base.GetSubKeyNames()) {
            $key = $base.OpenSubKey($k)
            if (-not $key) { continue }
            $e = [ordered]@{ Location = $r.Label; KeyName = $k }
            foreach ($v in 'DisplayName', 'DisplayVersion', 'Publisher', 'UninstallString', 'QuietUninstallString', 'InstallLocation', 'DisplayIcon', 'SystemComponent', 'WindowsInstaller') {
                $e[$v] = $key.GetValue($v)
            }
            if ($e.DisplayName) { $list["$($r.Label)\$k"] = $e }
        }
    }
    return $list
}

function Test-Detected($result) { return ($result.ExitCode -eq 0 -and $result.Output) }

$ps32 = Join-Path $env:WINDIR 'SysWOW64\WindowsPowerShell\v1.0\powershell.exe'
if (-not (Test-Path $ps32)) { $ps32 = Join-Path $env:WINDIR 'System32\WindowsPowerShell\v1.0\powershell.exe' }
$ps64 = Join-Path $env:WINDIR 'System32\WindowsPowerShell\v1.0\powershell.exe'
$verdict = 'PASS'
$learned = $null
$newEntries = @()

try {
    Write-Progress2 'Sandbox test started.'

    # 1. Unpack the .intunewin exactly as the Intune agent does.
    $pkg = Get-ChildItem -LiteralPath $Here -Filter '*.intunewin' -File | Select-Object -First 1
    Add-Type -AssemblyName System.IO.Compression, System.IO.Compression.FileSystem
    $zip = [IO.Compression.ZipFile]::OpenRead($pkg.FullName)
    try {
        $xmlEntry = $zip.Entries | Where-Object { $_.FullName -like '*Metadata/Detection.xml' } | Select-Object -First 1
        $encEntry = $zip.Entries | Where-Object { $_.FullName -like '*Contents/*.intunewin' } | Select-Object -First 1
        if (-not $xmlEntry -or -not $encEntry) { throw "$($pkg.Name) is not a .intunewin (no Detection.xml / Contents)." }
        $reader = New-Object IO.StreamReader($xmlEntry.Open())
        [xml]$detection = $reader.ReadToEnd(); $reader.Close()
        $encPath = Join-Path $work 'content.bin'
        [IO.Compression.ZipFileExtensions]::ExtractToFile($encEntry, $encPath, $true)
    } finally { $zip.Dispose() }
    $info = $detection.ApplicationInfo.EncryptionInfo

    $fs = [IO.File]::OpenRead($encPath)
    try {
        $storedMac = New-Object byte[] 32
        [void]$fs.Read($storedMac, 0, 32)
        $hmac = New-Object Security.Cryptography.HMACSHA256 (, [Convert]::FromBase64String($info.MacKey))
        $mac = $hmac.ComputeHash($fs)                 # over IV + ciphertext (the rest of the file)
        if ([Convert]::ToBase64String($mac) -ne [Convert]::ToBase64String($storedMac) -or [Convert]::ToBase64String($mac) -ne $info.Mac) {
            throw 'the HMAC does not match - the package is damaged'
        }
        $aes = [Security.Cryptography.Aes]::Create()
        $aes.Key = [Convert]::FromBase64String($info.EncryptionKey)
        $aes.IV  = [Convert]::FromBase64String($info.InitializationVector)
        $fs.Position = 48
        $payload = Join-Path $work 'payload.zip'
        $crypto = New-Object Security.Cryptography.CryptoStream($fs, $aes.CreateDecryptor(), 'Read')
        $outFs = [IO.File]::Create($payload)
        $crypto.CopyTo($outFs); $outFs.Close(); $crypto.Close()
    } finally { $fs.Dispose() }
    $content = Join-Path $work 'Content'
    [IO.Compression.ZipFile]::ExtractToDirectory($payload, $content)
    Add-Step 'Unpack' $true ("{0}: HMAC valid, decrypted, {1} file(s): {2}" -f $pkg.Name, (Get-ChildItem $content -Recurse -File).Count, ((Get-ChildItem $content -File).Name -join ', '))

    $detect = Join-Path $Here 'Detect.ps1'
    if (-not (Test-Path $detect)) { throw 'Detect.ps1 is missing next to the package.' }
    Copy-Item -LiteralPath $detect -Destination (Join-Path $work 'Detect.ps1') -Force
    $detectArgs = "-ExecutionPolicy Bypass -NoProfile -NonInteractive -File `"$(Join-Path $work 'Detect.ps1')`""

    # 2. Detection on a clean machine.
    $d = Invoke-AsSystem $ps64 $detectArgs $work $DetectTimeoutMinutes
    if (Test-Detected $d) { Add-Step 'Detect before install' $false "Detect.ps1 says the app is ALREADY installed on a clean Windows - the rule is too broad ($($d.Output))"; $verdict = 'FAIL' }
    else { Add-Step 'Detect before install' $true 'not installed, as expected' }

    # 3. Install, as SYSTEM, from 32-bit PowerShell - the way the Intune agent starts it.
    $before = Get-UninstallEntries
    Write-Progress2 "Installing (up to $InstallTimeoutMinutes minutes)..."
    $started = Get-Date
    $i = Invoke-AsSystem $ps32 '-ExecutionPolicy Bypass -NoProfile -NonInteractive -File .\Install.ps1' $content $InstallTimeoutMinutes
    $secs = [int]((Get-Date) - $started).TotalSeconds
    if ($i.TimedOut) {
        Add-Step 'Install' $false "still running after $InstallTimeoutMinutes minutes - it is probably waiting on a dialog that nobody can click as SYSTEM"; $verdict = 'FAIL'
    } else {
        $meaning = switch ($i.ExitCode) {
            0 { 'success' } 1707 { 'success' } 3010 { 'success, reboot required (soft reboot)' } 1641 { 'success, the installer started a reboot (hard reboot)' }
            1618 { 'another installation was in progress (Intune retries this)' } default { 'failure' }
        }
        $ok = $i.ExitCode -in 0, 1707, 3010, 1641
        Add-Step 'Install' $ok "exit code $($i.ExitCode) ($meaning) after $secs s"
        if (-not $ok) { $verdict = 'FAIL' }
    }

    # 4. Detection after install.
    $d = Invoke-AsSystem $ps64 $detectArgs $work $DetectTimeoutMinutes
    if (Test-Detected $d) { Add-Step 'Detect after install' $true "detected ($($d.Output))" }
    else { Add-Step 'Detect after install' $false 'Detect.ps1 does NOT see the app after the install - use the learned values below'; $verdict = 'FAIL' }

    # 5. What the install added to Programs and Features.
    $after = Get-UninstallEntries
    $newEntries = @($after.Keys | Where-Object { -not $before.ContainsKey($_) } | ForEach-Object { $after[$_] })
    if ($newEntries.Count) {
        # The app's own entry: visible in Programs and Features, preferring the one Detect.ps1 aims at.
        $pattern = ''
        $m = Select-String -LiteralPath $detect -Pattern "^\`$DisplayName\s*=\s*'(.*)'" | Select-Object -First 1
        if ($m) { $pattern = $m.Matches[0].Groups[1].Value -replace "''", "'" }
        $visible = @($newEntries | Where-Object { $_.SystemComponent -ne 1 })
        if (-not $visible.Count) { $visible = $newEntries }
        $main = $visible | Where-Object { $pattern -and $_.DisplayName -like $pattern } | Select-Object -First 1
        if (-not $main) { $main = $visible | Select-Object -First 1 }

        $isGuid = $main.KeyName -match '^\{[0-9A-Fa-f-]{36}\}$'
        $icon = "$($main.DisplayIcon)" -replace ',\s*-?\d+$', '' -replace '^"|"$', ''
        $file = $null
        if ($icon -match '\.exe$' -and (Test-Path -LiteralPath $icon)) { $file = $icon }
        elseif ($main.InstallLocation -and (Test-Path -LiteralPath $main.InstallLocation)) {
            $file = Get-ChildItem -LiteralPath $main.InstallLocation -Filter '*.exe' -File -ErrorAction SilentlyContinue |
                Where-Object { $_.Name -notmatch '^(unins|uninst|setup|update)' } | Sort-Object Length -Descending | Select-Object -First 1 -ExpandProperty FullName
        }
        $uninstall = $null
        if ($main.QuietUninstallString) { $uninstall = "$($main.QuietUninstallString)" }
        elseif ($isGuid -and ($main.WindowsInstaller -eq 1 -or "$($main.UninstallString)" -match '(?i)msiexec')) { $uninstall = "msiexec /x $($main.KeyName) /qn /norestart" }
        # A display name that carries the version ("7-Zip 24.08 (x64 edition)") becomes "7-Zip*", so the
        # rule still matches the next version. The name often shows fewer parts than DisplayVersion.
        $namePattern = "$($main.DisplayName)"
        $parts = "$($main.DisplayVersion)".Split('.')
        for ($n = $parts.Count; $n -ge 2; $n--) {
            $v = ($parts[0..($n - 1)] -join '.')
            $at = $namePattern.IndexOf($v)
            if ($at -gt 0) { $namePattern = $namePattern.Substring(0, $at).TrimEnd(' ', '-', '_', 'v', 'V') + '*'; break }
        }
        $learned = [ordered]@{
            displayName      = "$($main.DisplayName)"
            displayNameMatch = $namePattern
            displayVersion   = "$($main.DisplayVersion)"
            publisher        = "$($main.Publisher)"
            productCode      = $(if ($isGuid) { $main.KeyName } else { '' })
            registryKey      = "$($main.Location)\...\Uninstall\$($main.KeyName)"
            installLocation  = "$($main.InstallLocation)"
            detectFile       = "$file"
            uninstallCommand = "$uninstall"
            uninstallString  = "$($main.UninstallString)"
        }
        Add-Step 'Learn' $true ("Programs and Features gained {0} entr{1}; the app's is '{2}' {3}" -f $newEntries.Count, $(if ($newEntries.Count -eq 1) { 'y' } else { 'ies' }), $main.DisplayName, $main.DisplayVersion)
    } elseif ($verdict -eq 'PASS') {
        Add-Step 'Learn' $true 'the install added nothing to Programs and Features (a portable app, or a per-user install) - use File detection'
    }

    # 6. Uninstall, then detection again.
    $uninstallCmd = Select-String -LiteralPath (Join-Path $content 'Uninstall.ps1') -Pattern "^\`$FilePath\s*=\s*'(.*)'" | Select-Object -First 1
    if ($uninstallCmd -and $uninstallCmd.Matches[0].Groups[1].Value) {
        Write-Progress2 "Uninstalling (up to $InstallTimeoutMinutes minutes)..."
        $u = Invoke-AsSystem $ps32 '-ExecutionPolicy Bypass -NoProfile -NonInteractive -File .\Uninstall.ps1' $content $InstallTimeoutMinutes
        if ($u.TimedOut) { Add-Step 'Uninstall' $false "still running after $InstallTimeoutMinutes minutes - probably waiting on a dialog"; $verdict = 'FAIL' }
        else {
            $ok = $u.ExitCode -in 0, 1707, 3010, 1641
            Add-Step 'Uninstall' $ok "exit code $($u.ExitCode)"
            if (-not $ok) { $verdict = 'FAIL' }
        }
        $d = Invoke-AsSystem $ps64 $detectArgs $work $DetectTimeoutMinutes
        if (Test-Detected $d) { Add-Step 'Detect after uninstall' $false "Detect.ps1 still sees the app after the uninstall ($($d.Output))"; $verdict = 'FAIL' }
        else { Add-Step 'Detect after uninstall' $true 'not installed, as expected' }
    } else {
        Add-Step 'Uninstall' $false 'Uninstall.ps1 has no command - Intune could not remove this app. See the learned uninstall command below.'
        if ($verdict -eq 'PASS') { $verdict = 'PASS WITH WARNINGS' }
    }
} catch {
    Add-Step 'Error' $false $_.Exception.Message
    $verdict = 'FAIL'
}

# Logs: the scripts' own (C:\Intune\Logs) plus the raw output of each step.
$logDir = Join-Path $results 'Logs'
New-Item -ItemType Directory -Path $logDir -Force | Out-Null
Copy-Item -Path 'C:\Intune\Logs\*' -Destination $logDir -ErrorAction SilentlyContinue

$appName = "$($detection.ApplicationInfo.Name)"
$json = [ordered]@{ tool = 'SwitchHunt sandbox test'; version = 1; app = $appName; runAt = (Get-Date).ToString('s'); verdict = $verdict; steps = $steps; learned = $learned; newEntries = $newEntries }
$json | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath (Join-Path $results 'report.json') -Encoding UTF8

$txt = New-Object System.Text.StringBuilder
[void]$txt.AppendLine("SwitchHunt sandbox test - $appName")
[void]$txt.AppendLine("Result: $verdict")
[void]$txt.AppendLine('')
foreach ($s in $steps) { [void]$txt.AppendLine(("  [{0}] {1,-24} {2}" -f $(if ($s.ok) { 'PASS' } else { 'FAIL' }), $s.step, $s.detail)) }
if ($learned) {
    [void]$txt.AppendLine('')
    [void]$txt.AppendLine('LEARNED FROM THE INSTALL  (load report.json into the SwitchHunt page to use these)')
    foreach ($k in $learned.Keys) { if ($learned[$k]) { [void]$txt.AppendLine(("  {0,-18} {1}" -f $k, $learned[$k])) } }
}
[void]$txt.AppendLine('')
[void]$txt.AppendLine('Logs: the Logs folder next to this report')
$txt.ToString() | Set-Content -LiteralPath (Join-Path $results 'report.txt') -Encoding UTF8
Write-Progress2 "Done: $verdict"
