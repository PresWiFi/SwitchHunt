/**
 * Deployment scripts for the Intune bundle: Install.ps1 and Uninstall.ps1 (packaged INSIDE the
 * .intunewin next to the installer, and run by Intune), Detect.ps1 (uploaded to Intune as a custom
 * detection script) and a README with the settings to enter in the portal.
 *
 * Every script logs to C:\Intune\Logs on the device. Pure string templating, like psadt.ts - the
 * scripts are written here in the page and only shipped to the server to be zipped.
 */
import type { DetectionKind } from './psadt';
import sandboxScript from './sandbox/Test-InSandbox.ps1?raw';
import sandboxLauncher from './sandbox/Test-InSandbox.cmd?raw';

export const LOG_ROOT = 'C:\\Intune\\Logs';

export interface DeployScriptInput {
  appName: string;
  version: string;
  /** The installer's file name as packaged. */
  fileName: string;
  /** Full silent command lines, as shown on the page (CMD form). Uninstall may be empty. */
  install: string;
  uninstall: string;
  msiProductCode?: string;
  /** Detection rule picked on the page, and the value entered for it there. */
  detection: DetectionKind;
  /** File rule: a file the app installs. */
  detectPath?: string;
  /** Registry rule: wildcard pattern for the "Programs and Features" display name. Default: guessAppName(appName) + '*'. */
  detectName?: string;
  /** Registry and MSI rules: lowest version that counts as installed. Empty = any. */
  minVersion?: string;
  /** A Logo.png goes in the bundle beside the scripts. */
  hasLogo?: boolean;
  /** PowerShell run by Install.ps1 after a successful install (e.g. add users to a group). */
  postInstall?: string;
  /** What the installer puts on the machine, as read from the file - for the Intune requirement rule. */
  arch?: { value: 'x64' | 'x86' | 'arm64' | 'unknown'; certainty: 'certain' | 'likely' | 'unknown' };
}

export interface TextFile { name: string; text: string; }
/** A file beside the package in the bundle zip: a script, or an image (the logo) as base64. */
export type BundleFile = TextFile | { name: string; base64: string };

/**
 * The app's name as "Programs and Features" is likely to show it, from the installer's ProductName or,
 * failing that, its file name: "Docker Desktop Installer.exe" -> "Docker Desktop",
 * "Firefox Setup 131.0.exe" -> "Firefox". A guess - the page lets you correct it.
 */
export function guessAppName(name: string): string {
  const cleaned = name
    .replace(/\.(exe|msi|msix|appx)$/i, '')
    .replace(/[_]+/g, ' ')
    .replace(/(^|[\s.-])v?\d+(\.\d+)+[a-z]?(?=$|[\s.-])/gi, ' ')                        // versions
    .replace(/(^|[\s.-])(x64|x86|win64|win32|amd64|arm64|64-?bit|32-?bit)(?=$|[\s.-])/gi, ' ')
    .replace(/(^|[\s.-])(setup|installer|install)(?=$|[\s.-])/gi, ' ')
    .replace(/\s*[-.]\s*$|^\s*[-.]\s*/g, '')
    .replace(/\s{2,}/g, ' ')
    .trim();
  return cleaned || name;
}

const q = (s: string): string => `'${s.replace(/'/g, "''")}'`; // PowerShell single-quoted literal

/** Split a command line into the program and the rest. The program may be quoted. */
function splitCommand(cmd: string): [string, string] {
  cmd = cmd.trim();
  if (cmd.startsWith('"')) {
    const end = cmd.indexOf('"', 1);
    return end < 0 ? [cmd.slice(1), ''] : [cmd.slice(1, end), cmd.slice(end + 1).trim()];
  }
  const sp = cmd.search(/\s/);
  return sp < 0 ? [cmd, ''] : [cmd.slice(0, sp), cmd.slice(sp + 1).trim()];
}

/** A file-name-safe label for the log files, e.g. "7-Zip_24.08". */
function logName(i: DeployScriptInput): string {
  const base = [i.appName, i.version].filter(Boolean).join('_').replace(/[^A-Za-z0-9.\-]+/g, '_').replace(/^_+|_+$/g, '');
  return base || 'App';
}

/** Exit codes Intune treats as success by default: 0, 1707, 3010 (soft reboot), 1641 (hard reboot). */
const SUCCESS_CODES = '0, 1707, 3010, 1641';

/** The post-install step, as a function in Install.ps1 - the user's PowerShell, indented. */
function postInstallBlock(code: string): string {
  const body = code.replace(/\r\n?/g, '\n').split('\n').map((l) => (l.trim() ? '    ' + l : '')).join('\n');
  return `
# Post-install step, entered on the SwitchHunt page. Runs as SYSTEM, only after a successful install.
# If it throws, the install is reported to Intune as failed (exit code 1) so it gets attention.
function Invoke-PostInstall {
${body}
}
`;
}

function wrapper(action: 'Install' | 'Uninstall', i: DeployScriptInput): string {
  const command = action === 'Install' ? i.install : i.uninstall;
  const [file, args] = splitCommand(command);
  const post = action === 'Install' && i.postInstall?.trim() ? i.postInstall : '';
  return `<#
    ${action} wrapper for ${i.appName}${i.version ? ' ' + i.version : ''}
    Generated by SwitchHunt.

    Intune command:  powershell.exe -ExecutionPolicy Bypass -NoProfile -NonInteractive -File .\\${action}.ps1
    Runs:            ${command || '(no command known - set $FilePath and $Arguments below)'}
    Exit code:       the installer's own exit code is returned to Intune unchanged${post ? ' (or 1 if the post-install step fails)' : ''}.
    Logs:            ${LOG_ROOT}\\${logName(i)}-${action}.log
#>
$Action    = ${q(action)}
$FilePath  = ${q(file)}        # looked up in this folder first, then on PATH; %VARIABLES% are expanded
$Arguments = ${q(args)}
$LogRoot   = ${q(LOG_ROOT)}
$LogName   = ${q(logName(i))}

# Intune starts 32-bit PowerShell. Relaunch as 64-bit so %ProgramFiles% and the registry are not redirected.
if ($env:PROCESSOR_ARCHITEW6432) {
    $powershell64 = Join-Path $env:WINDIR 'SysNative\\WindowsPowerShell\\v1.0\\powershell.exe'
    if (Test-Path $powershell64) {
        & $powershell64 -ExecutionPolicy Bypass -NoProfile -NonInteractive -File $PSCommandPath
        exit $LASTEXITCODE
    }
}

$LogDir = $LogRoot
try { if (-not (Test-Path -LiteralPath $LogDir)) { New-Item -Path $LogDir -ItemType Directory -Force -ErrorAction Stop | Out-Null } }
catch { $LogDir = $env:TEMP }
$Log    = Join-Path $LogDir "$LogName-$Action.log"
$MsiLog = Join-Path $LogDir "$LogName-$Action-msi.log"

${post ? postInstallBlock(post) : ''}
$exitCode = 1
try { Start-Transcript -Path $Log -Append -Force | Out-Null } catch { }
try {
    Write-Output "$Action started as $([Security.Principal.WindowsIdentity]::GetCurrent().Name) from $PSScriptRoot"
    if (-not $FilePath) { throw "No $Action command is set. Edit \`$FilePath and \`$Arguments at the top of $Action.ps1." }
    if ("$FilePath $Arguments" -match '<[^>]+>') { throw "The $Action command still contains a <placeholder>. Edit \`$FilePath and \`$Arguments at the top of $Action.ps1." }

    $file = [Environment]::ExpandEnvironmentVariables($FilePath)
    if (-not [IO.Path]::IsPathRooted($file) -and (Test-Path -LiteralPath (Join-Path $PSScriptRoot $file) -PathType Leaf)) {
        $file = Join-Path $PSScriptRoot $file
    }
    $argumentLine = [Environment]::ExpandEnvironmentVariables($Arguments).Trim()
    # Windows Installer: add a verbose log unless the command already asks for one.
    if ([IO.Path]::GetFileNameWithoutExtension($file) -eq 'msiexec' -and $argumentLine -notmatch '(?i)(^|\\s)/l[a-z*!+]*\\s') {
        $argumentLine = "$argumentLine /L*v \`"$MsiLog\`""
    }

    Write-Output "Running: \`"$file\`" $argumentLine"
    $start = @{ FilePath = $file; WorkingDirectory = $PSScriptRoot; PassThru = $true }
    if ($argumentLine) { $start.ArgumentList = $argumentLine }
    $process = Start-Process @start
    $null = $process.Handle      # keeps the handle open so ExitCode is available after the wait
    $process.WaitForExit()
    $exitCode = $process.ExitCode
    Write-Output "$Action finished with exit code $exitCode"${post ? `
    if ($exitCode -in ${SUCCESS_CODES}) {
        Write-Output 'Running the post-install step'
        try { Invoke-PostInstall; Write-Output 'Post-install step finished' }
        catch { Write-Output "ERROR in the post-install step: $($_.Exception.Message)"; $exitCode = 1 }
    }` : ''}
}
catch {
    Write-Output "ERROR: $($_.Exception.Message)"
    $exitCode = 1
}
finally {
    try { Stop-Transcript | Out-Null } catch { }
}
exit $exitCode
`;
}

/** Which of the three checks Detect.ps1 will actually use, given what was entered on the page. */
function detectionMode(i: DeployScriptInput): 'file' | 'productCode' | 'displayName' {
  if (i.detection === 'file' && i.detectPath) return 'file';
  if (i.detection === 'msi' && i.msiProductCode) return 'productCode';
  return 'displayName';
}

const displayNamePattern = (i: DeployScriptInput): string => i.detectName?.trim() || guessAppName(i.appName) + '*';

function detectScript(i: DeployScriptInput): string {
  const mode = detectionMode(i);
  return `<#
    Intune detection script for ${i.appName}${i.version ? ' ' + i.version : ''}
    Generated by SwitchHunt.

    Detected = exit code 0 with a line written to the output. Checks, in this order: the file path
    if one is set; otherwise the machine-wide "Programs and Features" entries (64-bit and 32-bit)
    for the product code if one is set, else for the display name - at the minimum version, if set.
    Logs:  ${LOG_ROOT}\\${logName(i)}-Detect.log
#>
$DetectFile     = ${q(mode === 'file' ? i.detectPath! : '')}     # a file the app installs; %VARIABLES% are expanded. Leave empty to use the registry
$ProductCode    = ${q(mode === 'productCode' ? i.msiProductCode! : '')}     # MSI product code; leave empty to match on the display name
$DisplayName    = ${q(displayNamePattern(i))}     # wildcard pattern matched against DisplayName
$MinimumVersion = ${q(mode === 'file' ? '' : i.minVersion?.trim() ?? '')}     # e.g. ${q(i.version || '1.2.3')}; leave empty to accept any version
$LogRoot        = ${q(LOG_ROOT)}
$LogName        = ${q(logName(i))}

# Written with Add-Content, not to the output: any output line tells Intune the app is installed.
function Write-Log([string]$Text) {
    try {
        if (-not (Test-Path -LiteralPath $LogRoot)) { New-Item -Path $LogRoot -ItemType Directory -Force -ErrorAction Stop | Out-Null }
        Add-Content -LiteralPath (Join-Path $LogRoot "$LogName-Detect.log") -Value "$(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')  $Text" -ErrorAction Stop
    } catch { }
}

function ConvertTo-Version([string]$Text) {
    if ($Text -match '\\d+(\\.\\d+){0,3}') {
        $value = $Matches[0]
        if ($value -notmatch '\\.') { $value = "$value.0" }
        try { return [version]$value } catch { }
    }
    return $null
}

if ($DetectFile) {
    $path = [Environment]::ExpandEnvironmentVariables($DetectFile)
    if (Test-Path -LiteralPath $path) {
        Write-Log "Detected: $path exists"
        Write-Output "Detected $path"
        exit 0
    }
    Write-Log "Not detected: $path does not exist"
    exit 1
}

$required = ConvertTo-Version $MinimumVersion
foreach ($view in 'Registry64', 'Registry32') {
    try { $hklm = [Microsoft.Win32.RegistryKey]::OpenBaseKey('LocalMachine', $view) } catch { continue }
    $uninstall = $hklm.OpenSubKey('SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\Uninstall')
    if (-not $uninstall) { continue }
    foreach ($keyName in $uninstall.GetSubKeyNames()) {
        $key = $uninstall.OpenSubKey($keyName)
        if (-not $key) { continue }
        $name = [string]$key.GetValue('DisplayName')
        $version = [string]$key.GetValue('DisplayVersion')
        if ($ProductCode) { $isMatch = $keyName -eq $ProductCode } else { $isMatch = $name -and $name -like $DisplayName }
        if (-not $isMatch) { continue }

        $installed = ConvertTo-Version $version
        if ($required -and (-not $installed -or $installed -lt $required)) {
            Write-Log "Found $name $version ($view) but it is below the minimum version $MinimumVersion"
            continue
        }
        Write-Log "Detected: $name $version ($view)"
        Write-Output "Detected $name $version"
        exit 0
    }
}
if ($ProductCode) { Write-Log "Not detected: no uninstall entry for product code $ProductCode" }
else { Write-Log "Not detected: no uninstall entry with a display name like '$DisplayName'" }
exit 1
`;
}

const ARCH_RULE: Record<string, string> = {
  x64: '64-bit only (x64; add arm64 if it also runs under ARM emulation)',
  x86: '32-bit and 64-bit (x86 and x64)',
  arm64: 'ARM64',
};

function readme(i: DeployScriptInput, packageName: string): string {
  const mode = detectionMode(i);
  const arch = i.arch && i.arch.value !== 'unknown' ? ARCH_RULE[i.arch.value] + (i.arch.certainty === 'likely' ? '  - a guess from the name, check it' : '') : '';
  const log = logName(i);
  const detects = mode === 'file' ? `the file ${i.detectPath} exists`
    : mode === 'productCode' ? `an installed product with the MSI product code ${i.msiProductCode}`
    : `an installed program whose name in "Programs and Features" matches "${displayNamePattern(i)}"`;
  const minVer = mode !== 'file' && i.minVersion?.trim() ? `, version ${i.minVersion.trim()} or later` : '';
  const warnings: string[] = [];
  if (!i.uninstall) warnings.push('No uninstall command was given. Uninstall.ps1 fails until it has one: enter it in the Uninstall box on the SwitchHunt page and build the bundle again (the copy Intune runs is the one inside the .intunewin).');
  if (/<[^>]+>/.test(i.install + ' ' + i.uninstall)) warnings.push('A command contains a <placeholder> that must be replaced with your own value. The scripts refuse to run until it is: fix the command in the box on the SwitchHunt page and build the bundle again.');
  if (i.detection === 'file' && !i.detectPath) warnings.push('File detection was picked but no file path was entered, so Detect.ps1 falls back to the display name below.');
  if (i.detection === 'msi' && !i.msiProductCode) warnings.push('MSI detection was picked but there is no product code, so Detect.ps1 falls back to the display name below.');
  if (mode === 'displayName' && !i.detectName?.trim()) warnings.push(`Detect.ps1 matches on the display name "${displayNamePattern(i)}", which is a guess from the installer's metadata. Install the app once on a test machine and check the name under "Programs and Features" (or set $DetectFile to a file it installs) before you rely on it.`);
  if (/<[^>]+>/.test((mode === 'file' ? i.detectPath : displayNamePattern(i)) ?? '')) warnings.push('The detection rule still contains a <placeholder>. Fix it on the SwitchHunt page and build the bundle again, or Detect.ps1 never reports the app as installed.');
  return `${i.appName}${i.version ? ' ' + i.version : ''} - Intune Win32 app bundle
Generated by SwitchHunt.

FILES
  ${packageName}
      Upload this as the app package. It contains ${i.fileName}, Install.ps1 and Uninstall.ps1.
  Detect.ps1
      Upload this as the custom detection script.
  Install.ps1, Uninstall.ps1
      Copies of the two scripts inside the package, for reference. Editing these copies changes
      nothing - change the commands on the SwitchHunt page and build the bundle again.
  Test-InSandbox.cmd, Test-InSandbox.ps1
      Double-click Test-InSandbox.cmd to try the package in Windows Sandbox first (see below).${i.hasLogo ? `
  Logo.png
      The installer's icon. Upload it as the Logo under App information.` : ''}

INTUNE SETTINGS  (Apps > Windows > Add > Windows app (Win32))
  Install command      powershell.exe -ExecutionPolicy Bypass -NoProfile -NonInteractive -File .\\Install.ps1
  Uninstall command    powershell.exe -ExecutionPolicy Bypass -NoProfile -NonInteractive -File .\\Uninstall.ps1
  Install behavior     System
  Detection rules      Use a custom detection script > Detect.ps1
                       Run script as 32-bit process on 64-bit clients: No
                       Enforce script signature check: No
  Requirements         Operating system architecture: ${arch || 'the installer does not say - x64 is the usual choice'}
                       Minimum operating system: the oldest Windows version you support
  Return codes         Keep Intune's defaults - the scripts pass the installer's code through:
                         0 Success, 1707 Success, 3010 Soft reboot, 1641 Hard reboot, 1618 Retry
                       Add any other code this installer documents as success (as Success).

WHAT THE SCRIPTS DO
  Install.ps1     runs:  ${i.install || '(nothing - no command known)'}
  Uninstall.ps1   runs:  ${i.uninstall || '(nothing - no command known)'}
  Detect.ps1      reports the app as installed when it finds ${detects}${minVer}.
  Install and uninstall return the installer's own exit code to Intune unchanged.${i.postInstall?.trim() ? `
  After a successful install, Install.ps1 also runs the post-install step (as SYSTEM):
${i.postInstall.trim().split(/\r?\n/).map((l) => '      ' + l).join('\n')}
  If that step fails, Install.ps1 returns 1.` : ''}

TEST IT FIRST  (Windows 10/11 Pro or Enterprise, with the Windows Sandbox feature turned on)
  Unzip this bundle, then double-click Test-InSandbox.cmd. A fresh Windows Sandbox opens and runs
  the package the way Intune would, as SYSTEM: detect (expect not installed), install, detect
  (expect installed), uninstall, detect (expect not installed). The results - and the exact
  display name, version, product code, uninstall command and program file the install created -
  land in SandboxResults\\<date-time>\\. Load its report.json on the SwitchHunt page ("Load sandbox
  results") to use those values, and build the bundle again.
  It cannot reboot, and apps that need virtualization themselves (Docker Desktop, WSL) will not run
  in the Sandbox.

LOGS ON THE DEVICE  (${LOG_ROOT})
  ${log}-Install.log        transcript of every install run
  ${log}-Uninstall.log      transcript of every uninstall run
  ${log}-Detect.log         one line per detection check
  ${log}-Install-msi.log    verbose Windows Installer log (MSI installs only; -Uninstall-msi.log likewise)
${warnings.length ? '\nBEFORE YOU DEPLOY\n' + warnings.map((w) => '  * ' + w).join('\n') + '\n' : ''}
Test the package on a throwaway VM before assigning it. The switches are detected or curated
best-effort; a wrong one ships a broken install to every machine.
`;
}

/**
 * The scripts for one app. `payloadFiles` belong inside the .intunewin beside the installer;
 * `bundleFiles` sit next to the package in the zip handed to the admin.
 */
export function generateDeployScripts(i: DeployScriptInput, packageName: string): { payloadFiles: TextFile[]; bundleFiles: BundleFile[] } {
  const install = { name: 'Install.ps1', text: wrapper('Install', i) };
  const uninstall = { name: 'Uninstall.ps1', text: wrapper('Uninstall', i) };
  return {
    payloadFiles: [install, uninstall],
    bundleFiles: [
      install, uninstall, { name: 'Detect.ps1', text: detectScript(i) }, { name: 'README.txt', text: readme(i, packageName) },
      { name: 'Test-InSandbox.cmd', text: sandboxLauncher }, { name: 'Test-InSandbox.ps1', text: sandboxScript },
    ],
  };
}
